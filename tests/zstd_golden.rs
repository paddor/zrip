/// Decodes `frame` with every zrip decoder: one-shot, push and reader.
fn zrip_decodes(frame: &[u8]) -> [Result<Vec<u8>, String>; 3] {
    let one_shot = zrip::decompress(frame).map_err(|e| format!("{e:?}"));
    let mut dec = PushDecoder::new();
    let mut out = Vec::new();
    let push = dec
        .decode_to_vec(frame, &mut out)
        .and_then(|_| dec.finish())
        .map(|()| out)
        .map_err(|e| format!("{e:?}"));
    let mut out = Vec::new();
    let reader = zrip::FrameDecoder::new(frame)
        .read_to_end(&mut out)
        .map(|_| out)
        .map_err(|e| e.to_string());
    [one_shot, push, reader]
}

#[test]
fn golden_decompression() {
    for (name, frame) in [
        ("empty-block", EMPTY_BLOCK),
        ("rle-first-block", RLE_FIRST_BLOCK),
        ("zeroSeq_2B", ZERO_SEQ_2B),
    ] {
        let expected = zstd::stream::decode_all(frame).unwrap();
        for (path, got) in ["one-shot", "push", "reader"]
            .iter()
            .zip(zrip_decodes(frame))
        {
            assert_eq!(got.as_deref(), Ok(&expected[..]), "{name} ({path})");
        }
    }
}

#[test]
fn golden_decompression_errors() {
    for (name, frame) in [
        ("off0.bin", OFF0),
        ("truncated_huff_state", TRUNCATED_HUFF_STATE),
        ("zeroSeq_extraneous", ZERO_SEQ_EXTRANEOUS),
    ] {
        assert!(zstd::stream::decode_all(frame).is_err(), "C rejects {name}");
        for (path, got) in ["one-shot", "push", "reader"]
            .iter()
            .zip(zrip_decodes(frame))
        {
            assert!(got.is_err(), "{name} ({path}) decoded: {got:?}");
        }
    }
}

#[test]
fn golden_compression() {
    for (name, data) in [
        ("http", HTTP),
        ("huffman-compressed-larger", HUFFMAN_COMPRESSED_LARGER),
    ] {
        for level in -7..=4 {
            let frame = zrip::compress(data, level).unwrap();
            assert_eq!(
                zstd::stream::decode_all(&frame[..]).unwrap(),
                data,
                "{name} L{level}"
            );
            assert_eq!(zrip::decompress(&frame).unwrap(), data, "{name} L{level}");
        }
    }
}

/// The dictionary's Huffman weights sum to 2048, so the implied last
/// weight makes `Max_Number_of_Bits` 12. The format allows at most 11 and
/// calls such a description corrupted; C zstd takes up to 12.
#[test]
fn golden_dictionary_over_11_bits_is_rejected() {
    assert_eq!(
        Dictionary::from_bytes(HTTP_DICT_MISSING_SYMBOLS).err(),
        Some(zrip::DecompressError::BadHuffmanWeights)
    );
    let mut c = zstd::bulk::Compressor::with_dictionary(3, HTTP_DICT_MISSING_SYMBOLS).unwrap();
    assert!(c.compress(HTTP).is_ok(), "C zstd takes the dictionary");
}
